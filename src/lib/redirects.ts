/**
 * Permanent (308) redirects. Old French slugs → English slugs, trailing slash and
 * upper-case page paths → their canonical form, plus the
 * host hop to SITE_URL once a custom domain is live. Always a single hop:
 * `whofundsoss.vercel.app/classement` goes straight to `{SITE_URL}/ranking`.
 */
import { SLUG_RENAMED_FROM, SLUG_RENAMES } from "@/lib/slug-aliases";

export const SLUG_REDIRECTS: Record<string, string> = {
  "/classement": "/ranking",
  "/methode": "/method",
  "/mouvements": "/movements",
  "/mysteres": "/mysteries",
  "/graphe": "/graph",
  // Catalog merge 2026-10-06: nx-by-nrwl → nrwl (same nx.dev / GH login nrwl)
  "/company/nx-by-nrwl": "/company/nrwl",
};

/**
 * Company slugs changed by canonical slugify (accents, homoglyphs), old -> new.
 * Generated by scripts/weekly/slug_renames.py. Conditional so it is safe both
 * before and after a catalog rebuild: we 308 old -> new once the new key exists
 * and the old one is gone, and (until then) new -> old so both URLs work.
 */
export const COMPANY_SLUG_RENAMES: ReadonlyMap<string, string> = SLUG_RENAMES;

/** Paths keyed by a company slug that follow slug renames (page + API). */
const RENAMEABLE = /^\/(company|api\/sponsors|api\/v1\/companies)\/([^/]+)(\/sponsorships)?$/;

/** True when the path is one companyRenameTarget may rewrite (lets callers skip the catalog load). */
export function isRenameablePath(path: string): boolean {
  return RENAMEABLE.test(path.toLowerCase());
}

/** `/company/<slug>` (or `/api/sponsors/<slug>`, `/api/v1/companies/<slug>[/sponsorships]`) rename hop, or null. `exists` says whether the catalog has a key. */
export function companyRenameTarget(path: string, exists: (slug: string) => boolean): string | null {
  const m = RENAMEABLE.exec(path);
  if (!m) return null;
  const [, base, slug, tail = ""] = m as unknown as [string, string, string, string?];
  if (exists(slug)) return null;
  const forward = SLUG_RENAMES.get(slug);
  if (forward && exists(forward)) return `/${base}/${forward}${tail}`;
  // Pre-rebuild fallback (new -> old) only for the page, never for the API.
  const back = base === "company" ? SLUG_RENAMED_FROM.get(slug) : undefined;
  if (back && exists(back)) return `/${base}/${back}${tail}`;
  return null;
}

/** Production alias that should hop to SITE_URL when SITE_URL is another host. */
export const LEGACY_PROD_HOST = "whofundsoss.vercel.app";

function stripPort(host: string): string {
  return host.split(",")[0]!.trim().split(":")[0]!.toLowerCase();
}

/**
 * Returns the absolute redirect target, or null. Pure, so it is unit-tested
 * without a server (scripts/redirects.test.mjs mirrors these cases).
 */
export function redirectTarget(
  requestUrl: URL,
  hostHeader: string,
  siteUrl: string,
  companyExists?: (slug: string) => boolean,
): string | null {
  const host = stripPort(hostHeader || requestUrl.host);
  const site = new URL(siteUrl);
  const siteHost = site.host.toLowerCase();

  const rawPath = requestUrl.pathname;
  const trimmed = rawPath.length > 1 ? rawPath.replace(/\/+$/, "") : rawPath;
  const slugTarget =
    (Object.hasOwn(SLUG_REDIRECTS, trimmed.toLowerCase()) ? SLUG_REDIRECTS[trimmed.toLowerCase()] : undefined) ??
    (companyExists ? companyRenameTarget(trimmed.toLowerCase(), companyExists) : null) ??
    undefined;
  // Page routes are lowercase with no trailing slash. API, card and file URLs are left alone.
  const isPage = !/^\/(api|og|_)/i.test(trimmed) && !/\.[a-z0-9]+$/i.test(trimmed);
  const normalized = isPage ? trimmed.toLowerCase() : rawPath;
  const path = slugTarget ?? normalized;

  const hostHop =
    (host === LEGACY_PROD_HOST && siteHost !== LEGACY_PROD_HOST) ||
    (host.startsWith("www.") && host.slice(4) === siteHost);

  if (hostHop) return `${site.origin}${path}${requestUrl.search}`;
  if (slugTarget) return `${requestUrl.origin}${slugTarget}${requestUrl.search}`;
  if (isPage && normalized !== rawPath) return `${requestUrl.origin}${normalized}${requestUrl.search}`;
  return null;
}
